#!/usr/bin/env python3
"""Generate the moving source clips of the Pli product film.

Every clip is real generated video (Wan 2.2 image-to-video). Still images
are only start frames; a missing or failed generation stays missing and
scripts/build-product-film.py refuses to render. Provenance (generator,
model, prompt, seed, input hashes) is written next to each clip so an
unchanged shot is never generated twice.
"""
from pathlib import Path
import argparse, hashlib, json, shutil, subprocess, time

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / 'media/pli-film/production.json'
WORK = ROOT / '.tools/product-film'
GENERATORS = {
    'wan2.2-i2v': {'space': 'zerogpu-aoti/wan2-2-fp8da-aoti-faster',
                   'model': 'Wan-AI/Wan2.2-I2V-A14B (Lightning LoRA, fp8)', 'api': '/generate_video'},
    # Picture and sound from one model: the people's Korean dialogue, breathing and the car's
    # ambience are generated with the motion (no separate voice synthesis for the cast).
    'ltx2.3-av': {'space': 'Lightricks/LTX-2-3', 'model': 'Lightricks/LTX-2.3 (video + synchronized audio)',
                  'api': '/generate_video'},
    # Same family, distilled LTX-2 with joint audio; its fixed 3-second clips reserve less ZeroGPU time.
    'ltx2-turbo-av': {'space': 'alexnasa/ltx-2-TURBO', 'model': 'Lightricks/LTX-2 distilled (video + synchronized audio, 3 s)',
                      'api': '/generate_video'},
}
AUDIO_VISUAL = ('ltx2.3-av', 'ltx2-turbo-av')


def sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_plan(path: Path = PLAN) -> dict:
    plan = json.loads(Path(path).read_text())
    ids = [shot['id'] for shot in plan['shots']]
    if len(ids) != len(set(ids)):
        raise SystemExit('Duplicate shot id in plan')
    missing = {shot['keyframe'] for shot in plan['shots']} - plan['keyframes'].keys()
    if missing:
        raise SystemExit('Undeclared keyframe: ' + ', '.join(sorted(missing)))
    return plan


def keyframe_path(name: str) -> Path:
    return WORK / 'keyframes' / (name + '.png')


def build_keyframes(plan: dict) -> None:
    """Crop start frames from the declared still; resize only when asked."""
    from PIL import Image, ImageFilter
    (WORK / 'keyframes').mkdir(parents=True, exist_ok=True)
    for name, spec in plan['keyframes'].items():
        image = Image.open(ROOT / spec['source']).convert('RGB').crop(tuple(spec['crop']))
        if spec.get('size'):
            image = image.resize(tuple(spec['size']), Image.LANCZOS).filter(
                ImageFilter.UnsharpMask(radius=2, percent=60, threshold=2))
        image.save(keyframe_path(name))


def shot_inputs(plan: dict, shot: dict) -> dict:
    """Everything that determines the generated bytes, compared for reuse."""
    generator = GENERATORS[shot['generator']]
    inputs = {'generator': shot['generator'], 'space': generator['space'], 'model': generator['model'],
              'keyframeSha256': sha(keyframe_path(shot['keyframe'])), 'prompt': shot['prompt'],
              'seconds': shot['generateSeconds'], 'seed': shot['seed']}
    if shot['generator'] in AUDIO_VISUAL:
        return {**inputs, 'size': shot.get('size', [1024, 576])}
    return {**inputs, 'negativePrompt': plan['negativePrompt'], 'steps': shot.get('steps', 6)}


def clip_path(shot: dict) -> Path:
    return WORK / 'generated' / (shot['id'] + '.mp4')


def provenance_path(shot: dict) -> Path:
    return WORK / 'generated' / (shot['id'] + '.json')


def is_current(plan: dict, shot: dict) -> bool:
    clip, record = clip_path(shot), provenance_path(shot)
    if not clip.is_file() or not record.is_file():
        return False
    saved = json.loads(record.read_text())
    return saved.get('inputs') == shot_inputs(plan, shot) and saved.get('videoSha256') == sha(clip)


def write_provenance(plan: dict, shot: dict, elapsed: float) -> dict:
    clip = clip_path(shot)
    probe = json.loads(subprocess.check_output(
        ['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries',
         'stream=codec_name,width,height,nb_frames,r_frame_rate:format=duration', '-of', 'json', str(clip)]))
    record = {'shot': shot['id'], 'inputs': shot_inputs(plan, shot), 'videoSha256': sha(clip),
              'video': probe, 'elapsedSeconds': elapsed, 'createdAt': time.strftime('%Y-%m-%dT%H:%M:%S%z')}
    provenance_path(shot).write_text(json.dumps(record, ensure_ascii=False, indent=2))
    return record


def generate(plan: dict, shot: dict, token: str) -> dict:
    from gradio_client import Client, handle_file
    generator = GENERATORS[shot['generator']]
    client = Client(generator['space'], token=token, verbose=False)
    started = time.time()
    image = handle_file(str(keyframe_path(shot['keyframe'])))
    if shot['generator'] == 'ltx2.3-av':
        width, height = shot.get('size', [1024, 576])
        result = client.predict(input_image=image, prompt=shot['prompt'], duration=shot['generateSeconds'], enhance_prompt=False,
                                seed=shot['seed'], randomize_seed=False, height=height, width=width, api_name=generator['api'])
    elif shot['generator'] == 'ltx2-turbo-av':
        width, height = shot.get('size', [896, 512])
        result = client.predict(first_frame=image, end_frame=None, prompt=shot['prompt'], input_video=None,
                                generation_mode='Image-to-Video', enhance_prompt=False, seed=shot['seed'], randomize_seed=False,
                                height=height, width=width, camera_lora='No LoRA', audio_path=None, api_name=generator['api'])
    else:
        result = client.predict(input_image=image, prompt=shot['prompt'],
                                steps=shot.get('steps', 6), negative_prompt=plan['negativePrompt'],
                                duration_seconds=shot['generateSeconds'], guidance_scale=1, guidance_scale_2=1,
                                seed=shot['seed'], randomize_seed=False, api_name=generator['api'])
    first = result[0] if isinstance(result, (list, tuple)) else result
    produced = first['video'] if isinstance(first, dict) else first
    elapsed = round(time.time() - started, 1)
    partial = clip_path(shot).with_suffix('.part.mp4')
    shutil.copyfile(produced, partial)
    subprocess.run(['ffprobe', '-v', 'error', str(partial)], check=True)  # refuse truncated downloads
    if shot['generator'] in AUDIO_VISUAL and not subprocess.check_output(
            ['ffprobe', '-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=index', '-of', 'csv=p=0', str(partial)]).strip():
        raise RuntimeError('the audio-visual generator returned no sound')
    partial.replace(clip_path(shot))
    return write_provenance(plan, shot, elapsed)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plan', type=Path, default=PLAN)
    parser.add_argument('--only', help='comma separated shot ids')
    parser.add_argument('--check', action='store_true', help='report missing or stale shots without generating')
    args = parser.parse_args()
    plan = load_plan(args.plan)
    wanted = set(args.only.split(',')) if args.only else None
    unknown = (wanted or set()) - {s['id'] for s in plan['shots']}
    if unknown:
        raise SystemExit('Unknown shot: ' + ', '.join(sorted(unknown)))
    build_keyframes(plan)
    selected = [s for s in plan['shots'] if wanted is None or s['id'] in wanted]
    pending = [s for s in selected if not is_current(plan, s)]
    if args.check:
        print(json.dumps({'ready': not pending, 'pending': [s['id'] for s in pending]}, ensure_ascii=False))
        return 0 if not pending else 2
    token = (Path.home() / '.cache/huggingface/token').read_text().strip()
    (WORK / 'generated').mkdir(parents=True, exist_ok=True)
    failures = {}
    for shot in pending:
        try:
            record = generate(plan, shot, token)
            print(json.dumps({'shot': shot['id'], 'status': 'GENERATED', 'seconds': record['elapsedSeconds']}), flush=True)
        except Exception as error:  # report every failed shot; never substitute a still
            failures[shot['id']] = type(error).__name__ + ': ' + str(error)[:600]
            print(json.dumps({'shot': shot['id'], 'status': 'FAILED', 'error': failures[shot['id']]}, ensure_ascii=False), flush=True)
    return 1 if failures else 0


if __name__ == '__main__':
    raise SystemExit(main())
